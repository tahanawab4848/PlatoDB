import { useState } from "react";
import { motion, AnimatePresence } from "framer-motion";
import { X, FileText, Loader2 } from "lucide-react";
import { jsPDF } from "jspdf";
import mermaid from "mermaid";
import { useStore } from "../../store/useStore";

interface Props {
  isOpen: boolean;
  onClose: () => void;
  tables: any[];
}

export default function ExportReportModal({ isOpen, onClose, tables }: Props) {
  const { relations, currentUser, currentProjectId } = useStore();
  const [loading, setLoading] = useState(false);
  const [formData, setFormData] = useState({
    name: currentUser?.name || "Taha Nawab",
    regNo: "",
    projectName: "PlatoDB Project",
    extraNotes: ""
  });

  const generatePDF = async () => {
    setLoading(true);
    try {
      // 1. Generate Mermaid ERD
      let md = `erDiagram\n`;
      tables.forEach(t => {
        md += `  ${t.name} {\n`;
        t.columns.forEach((c: any) => {
          const cleanType = c.type.replace(/\s+/g, '');
          md += `    ${cleanType} ${c.name} ${c.isPK ? 'PK' : ''}\n`;
        });
        md += `  }\n`;
      });
      relations.forEach(r => {
        md += `  ${r.fromTable} ||--o{ ${r.toTable} : "${r.fromColumn}"\n`;
      });

      if (tables.length === 0) {
        throw new Error("No tables available to generate the report. Please design a database schema first.");
      }

      mermaid.initialize({ startOnLoad: false, theme: 'default' });
      const { svg } = await mermaid.render(`mermaid-export-${Date.now()}`, md);

      const match = svg.match(/viewBox="([^"]+)"/);
      let svgWidth = 1000, svgHeight = 800;
      if (match) {
        const parts = match[1].trim().split(/\s+/);
        svgWidth = parseFloat(parts[2]);
        svgHeight = parseFloat(parts[3]);
      }
      
      // Remove any existing width/height attributes to prevent invalid XML duplicates
      let cleanSvg = svg.replace(/width="[^"]+"/, '').replace(/height="[^"]+"/, '');
      const fixedSvg = cleanSvg.replace(/<svg([^>]*)>/, `<svg$1 width="${svgWidth}" height="${svgHeight}">`);

      const svg64 = btoa(unescape(encodeURIComponent(fixedSvg)));
      const image64 = 'data:image/svg+xml;base64,' + svg64;

      const img = new Image();
      img.src = image64;
      await new Promise((resolve, reject) => { img.onload = resolve; img.onerror = reject; });

      const scale = 2;
      const canvas = document.createElement('canvas');
      canvas.width = svgWidth * scale;
      canvas.height = svgHeight * scale;
      const ctx = canvas.getContext('2d');
      if (ctx) {
        ctx.scale(scale, scale);
        ctx.fillStyle = '#ffffff';
        ctx.fillRect(0, 0, svgWidth, svgHeight);
        ctx.drawImage(img, 0, 0, svgWidth, svgHeight);
      }
      const erdDataUrl = canvas.toDataURL('image/png', 1.0);

      // 2. Generate PDF Document
      const pdf = new jsPDF({ orientation: 'portrait', unit: 'pt', format: 'a4' });
      const margin = 40;
      const pageWidth = pdf.internal.pageSize.getWidth();
      const pageHeight = pdf.internal.pageSize.getHeight();
      let currentY = margin;

      const checkPageBreak = (neededSpace: number) => {
        if (currentY + neededSpace > pageHeight - margin) {
          pdf.addPage();
          currentY = margin;
        }
      };

      // Header
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(24);
      pdf.setTextColor(0);
      pdf.text("Project Architecture Report", margin, currentY + 20);
      currentY += 40;
      
      pdf.setFont("helvetica", "normal");
      pdf.setFontSize(10);
      pdf.setTextColor(100);
      pdf.text(`Generated by PlatoDB AI • ${new Date().toLocaleString()}`, margin, currentY);
      currentY += 30;

      // Metadata Section
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(12);
      pdf.setTextColor(0);
      pdf.text(`Project:`, margin, currentY);
      pdf.setFont("helvetica", "normal");
      pdf.text(formData.projectName, margin + 50, currentY);
      currentY += 15;
      
      pdf.setFont("helvetica", "bold");
      pdf.text(`Author:`, margin, currentY);
      pdf.setFont("helvetica", "normal");
      pdf.text(formData.name, margin + 50, currentY);
      currentY += 15;
      
      if (formData.regNo) {
        pdf.setFont("helvetica", "bold");
        pdf.text(`Reg No:`, margin, currentY);
        pdf.setFont("helvetica", "normal");
        pdf.text(formData.regNo, margin + 50, currentY);
        currentY += 15;
      }
      if (formData.extraNotes) {
        pdf.setFont("helvetica", "italic");
        pdf.text(`Notes: ${formData.extraNotes}`, margin, currentY);
        currentY += 15;
      }
      currentY += 15;

      // 1. ERD
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(18);
      pdf.setTextColor(0);
      pdf.text("1. Entity Relationship Diagram", margin, currentY);
      currentY += 20;

      const availableWidth = pageWidth - (margin * 2);
      const scaledHeight = (img.height * availableWidth) / img.width;
      
      checkPageBreak(scaledHeight + 40);
      pdf.addImage(erdDataUrl, 'PNG', margin, currentY, availableWidth, scaledHeight);
      currentY += scaledHeight + 40;

      // 2. Mongoose Models
      checkPageBreak(100);
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(18);
      pdf.setTextColor(0);
      pdf.text("2. Database Schemas (Mongoose)", margin, currentY);
      currentY += 30;

      tables.forEach(t => {
        checkPageBreak(150);
        pdf.setFont("helvetica", "bold");
        pdf.setFontSize(14);
        pdf.setTextColor(79, 70, 229);
        pdf.text(`${t.name} Collection`, margin, currentY);
        currentY += 20;

        pdf.setFont("courier", "normal");
        pdf.setFontSize(10);
        pdf.setTextColor(50);
        
        const schemaCode = [
          `const mongoose = require('mongoose');`,
          ``,
          `const ${t.name}Schema = new mongoose.Schema({`
        ];
        
        t.columns.filter((c: any) => !c.isPK).forEach((c: any) => {
          const typeMap: any = { String: 'String', Number: 'Number', Boolean: 'Boolean', Date: 'Date', ObjectId: 'mongoose.Schema.Types.ObjectId' };
          schemaCode.push(`  ${c.name}: { type: ${typeMap[c.type] || 'String'}${c.isUnique ? ', unique: true' : ''} },`);
        });
        schemaCode.push(`}, { timestamps: true });`);
        schemaCode.push(``);
        schemaCode.push(`module.exports = mongoose.model('${t.name}', ${t.name}Schema);`);

        const codeHeight = schemaCode.length * 14 + 10;
        pdf.setFillColor(248, 250, 252);
        pdf.setDrawColor(226, 232, 240);
        pdf.rect(margin, currentY - 10, availableWidth, codeHeight, 'FD');

        schemaCode.forEach(line => {
          checkPageBreak(15);
          pdf.text(line, margin + 15, currentY);
          currentY += 14;
        });
        currentY += 30;
      });

      // 3. REST APIs
      checkPageBreak(100);
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(18);
      pdf.setTextColor(0);
      pdf.text("3. REST API Specification", margin, currentY);
      currentY += 30;

      tables.forEach(t => {
        checkPageBreak(120);
        pdf.setFont("helvetica", "bold");
        pdf.setFontSize(14);
        pdf.setTextColor(225, 29, 72);
        pdf.text(`${t.name} Endpoints`, margin, currentY);
        currentY += 20;
        
        const endpoints = [
          { method: "GET", path: `/api/${t.name}`, desc: "Retrieve all records" },
          { method: "POST", path: `/api/${t.name}`, desc: "Create a new record" },
          { method: "GET", path: `/api/${t.name}/:id`, desc: "Retrieve a single record" },
          { method: "PUT", path: `/api/${t.name}/:id`, desc: "Update an existing record" },
          { method: "DELETE", path: `/api/${t.name}/:id`, desc: "Remove a record" }
        ];

        endpoints.forEach(ep => {
          checkPageBreak(20);
          pdf.setFont("courier", "bold");
          pdf.setTextColor(0);
          pdf.text(ep.method.padEnd(7), margin + 10, currentY);
          
          pdf.setFont("courier", "normal");
          pdf.setTextColor(79, 70, 229);
          pdf.text(ep.path.padEnd(25), margin + 60, currentY);
          
          pdf.setFont("helvetica", "normal");
          pdf.setFontSize(10);
          pdf.setTextColor(100);
          pdf.text(`→ ${ep.desc}`, margin + 220, currentY);
          
          currentY += 20;
        });
        currentY += 20;
      });

      // 4. Footer Links
      checkPageBreak(100);
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(14);
      pdf.setTextColor(0);
      pdf.text("Architect Details & Links", margin, currentY);
      currentY += 20;

      pdf.setFont("helvetica", "normal");
      pdf.setFontSize(10);
      pdf.setTextColor(0, 102, 204);
      pdf.text("LinkedIn: https://www.linkedin.com/in/tahanawab4848", margin, currentY);
      currentY += 15;
      pdf.text("Portfolio: https://taha-nawab-portfolio.vercel.app/", margin, currentY);
      currentY += 15;
      pdf.text("GitHub: https://www.github.com/tahanawab4848", margin, currentY);

      pdf.save(`${formData.projectName.replace(/\s+/g, '-')}-Report.pdf`);
      onClose();
    } catch (e: any) {
      console.error(e);
      alert(`Failed to generate PDF Report: ${e?.message || 'Unknown error. Check console for details.'}`);
    } finally {
      setLoading(false);
    }
  };

  return (
    <AnimatePresence>
      {isOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm">
          <motion.div initial={{ opacity: 0, scale: 0.95 }} animate={{ opacity: 1, scale: 1 }} exit={{ opacity: 0, scale: 0.95 }} className="w-full max-w-md bg-slate-900 border border-slate-800 rounded-2xl overflow-hidden shadow-2xl relative">
            <button onClick={onClose} className="absolute top-4 right-4 p-2 text-slate-400 hover:text-white rounded-xl hover:bg-slate-800 transition-colors z-10"><X className="w-5 h-5" /></button>
            <div className="p-6 pb-0">
              <div className="w-12 h-12 bg-emerald-500/20 rounded-xl flex items-center justify-center mb-4 border border-emerald-500/30">
                <FileText className="w-6 h-6 text-emerald-400" />
              </div>
              <h2 className="text-xl font-bold text-white mb-2">Export Project Report</h2>
              <p className="text-sm text-slate-400 mb-6">Enter metadata to be included at the beginning of the generated PDF architecture document.</p>
            </div>
            
            <div className="p-6 space-y-4">
              <div>
                <label className="block text-xs font-semibold text-slate-400 uppercase tracking-wider mb-2">Project Name</label>
                <input type="text" value={formData.projectName} onChange={e => setFormData({ ...formData, projectName: e.target.value })} className="w-full px-4 py-2 bg-slate-950 border border-slate-800 rounded-xl text-sm text-white focus:outline-none focus:border-emerald-500/50" placeholder="e.g. HumanityOS" />
              </div>
              <div>
                <label className="block text-xs font-semibold text-slate-400 uppercase tracking-wider mb-2">Author Name</label>
                <input type="text" value={formData.name} onChange={e => setFormData({ ...formData, name: e.target.value })} className="w-full px-4 py-2 bg-slate-950 border border-slate-800 rounded-xl text-sm text-white focus:outline-none focus:border-emerald-500/50" placeholder="John Doe" />
              </div>
              <div>
                <label className="block text-xs font-semibold text-slate-400 uppercase tracking-wider mb-2">Registration No. / ID</label>
                <input type="text" value={formData.regNo} onChange={e => setFormData({ ...formData, regNo: e.target.value })} className="w-full px-4 py-2 bg-slate-950 border border-slate-800 rounded-xl text-sm text-white focus:outline-none focus:border-emerald-500/50" placeholder="Optional" />
              </div>
              <div>
                <label className="block text-xs font-semibold text-slate-400 uppercase tracking-wider mb-2">Extra Notes</label>
                <textarea value={formData.extraNotes} onChange={e => setFormData({ ...formData, extraNotes: e.target.value })} className="w-full px-4 py-2 bg-slate-950 border border-slate-800 rounded-xl text-sm text-white focus:outline-none focus:border-emerald-500/50 resize-none h-20" placeholder="Any additional context for this report..."></textarea>
              </div>
            </div>

            <div className="p-4 bg-slate-950 border-t border-slate-800 flex justify-end gap-3">
              <button onClick={onClose} className="px-5 py-2 text-sm font-medium text-slate-400 hover:text-white transition-colors">Cancel</button>
              <button onClick={generatePDF} disabled={loading} className="px-5 py-2 text-sm font-semibold text-white bg-emerald-600 hover:bg-emerald-500 rounded-xl transition-colors disabled:opacity-50 flex items-center gap-2">
                {loading ? <><Loader2 className="w-4 h-4 animate-spin" /> Generating...</> : <><FileText className="w-4 h-4" /> Download PDF</>}
              </button>
            </div>
          </motion.div>
        </div>
      )}
    </AnimatePresence>
  );
}
